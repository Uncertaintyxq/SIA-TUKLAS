<?php

declare(strict_types=1);

/**
 * PreToolUse hook for Edit / Write / MultiEdit / NotebookEdit.
 *
 * Makes Claude Code ask the developer before it edits a file when:
 *   - the current branch is the main branch,
 *   - another active branch / open PR is changing the same file, or
 *   - the file is a shared "hot file" listed in .claude/scope.json.
 *
 * Each file is asked about once per session; after that the edit proceeds.
 * The hook never blocks on errors — if anything goes wrong it lets the edit through.
 */

require __DIR__.'/lib.php';

$input = json_decode((string) stream_get_contents(STDIN), true);
if (! is_array($input)) {
    exit(0);
}

$toolInput = (array) ($input['tool_input'] ?? []);
$rawPath = (string) ($toolInput['file_path'] ?? $toolInput['notebook_path'] ?? '');
if ($rawPath === '') {
    exit(0);
}

$projectDir = project_dir();
$path = to_repo_path($rawPath, $projectDir);
if ($path === null || str_starts_with($path, '.claude/.cache/') || ! is_git_repo($projectDir)) {
    exit(0);
}

$config = load_config($projectDir);
$reasons = [];
$keys = [];

$branch = current_branch($projectDir);
if ($config['protectMain'] && $branch === $config['mainBranch']) {
    $reasons[] = "You are on '{$branch}'. Task work belongs on its own branch (use /start-task).";
    $keys[] = 'main';
}

$snap = load_or_build_snapshot($projectDir, $config);
$touchedBy = [];
foreach ((array) ($snap['others'] ?? []) as $o) {
    if (in_array($path, (array) $o['files'], true)) {
        $touchedBy[] = describe_other($o);
    }
}
if ($touchedBy !== []) {
    $reasons[] = "{$path} is also being changed on: ".implode('; ', $touchedBy).'. Editing it risks a merge conflict.';
    $keys[] = 'overlap';
}

if (($config['hotFileMode'] ?? 'ask') === 'ask' && matches_any($path, (array) $config['hotFiles'])) {
    $reasons[] = "{$path} is a shared hot file. Keep the change minimal (append-only if possible) and mention it in the PR.";
    $keys[] = 'hot';
}

if ($reasons === []) {
    exit(0);
}

// Only ask once per file per session.
$session = preg_replace('/[^A-Za-z0-9_-]/', '', (string) ($input['session_id'] ?? 'default')) ?: 'default';
$ackFile = $projectDir."/.claude/.cache/acks/{$session}.json";
$acks = is_file($ackFile) ? (array) json_decode((string) file_get_contents($ackFile), true) : [];
$ackKey = $path.'|'.implode(',', $keys);
if (in_array($ackKey, $acks, true)) {
    exit(0);
}
$acks[] = $ackKey;
@mkdir(dirname($ackFile), 0775, true);
@file_put_contents($ackFile, json_encode(array_values($acks)));

$reason = 'Scope check: '.implode(' ', $reasons);

echo json_encode([
    'hookSpecificOutput' => [
        'hookEventName' => 'PreToolUse',
        'permissionDecision' => 'ask',
        'permissionDecisionReason' => $reason,
        'additionalContext' => $reason.' If the developer declines, do not edit this file; propose an alternative (new file, separate small PR, or waiting for the other branch to merge).',
    ],
], JSON_UNESCAPED_SLASHES), "\n";
exit(0);
